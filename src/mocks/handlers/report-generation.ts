import { getBfarsReport } from "@/lib/constants/bfars";
import type { GeneratedReport } from "@/features/reports/types";
import { describeBfarsPeriod, toHistoryFormat, type GenerateBfarsRequest } from "@/services/bfars.service";
import { db, getMockSessionUserName } from "../services/db";
import { MockHttpError, route } from "../services/http";

function nextGeneratedId() {
  const max = db.reportHistory.map((r) => Number(r.id.replace(/\D/g, "")) || 0).reduce((a, b) => Math.max(a, b), 0);
  return `gen-${String(max + 1).padStart(4, "0")}`;
}

/** BFARS generation log and generated-report downloads. */
export const reportGenerationHandlers = [
  route<GenerateBfarsRequest>("POST", "/bfars/:id/generate", ({ params, body }): GeneratedReport => {
    const meta = getBfarsReport(params.id);
    if (!meta) throw new MockHttpError(404, "Report not found.");
    if (!body?.params || typeof body.params !== "object") {
      throw new MockHttpError(422, "Report parameters are required.", { params: "Select the report parameters." });
    }
    if (!body.format) throw new MockHttpError(422, "Choose an output format.", { format: "Choose an output format." });
    const record: GeneratedReport = {
      id: nextGeneratedId(),
      reportId: `rpt-${meta.id}`,
      reportName: `BFARS ${meta.number} – ${meta.code}`,
      period: describeBfarsPeriod(body.params),
      format: toHistoryFormat(body.format),
      generatedAt: new Date().toISOString(),
      generatedBy: getMockSessionUserName(),
      status: "Ready",
      parameters: { ...body.params, ...(body.options ? { options: body.options } : {}) },
    };
    db.reportHistory.unshift(record);
    return record;
  }),

  route("GET", "/bfars/:id/generated", ({ params }): GeneratedReport[] => {
    if (!getBfarsReport(params.id)) throw new MockHttpError(404, "Report not found.");
    return db.reportHistory
      .filter((r) => r.reportId === `rpt-${params.id}`)
      .sort((a, b) => b.generatedAt.localeCompare(a.generatedAt));
  }),

  /**
   * The mock has no stored files, so it returns a small CSV describing the
   * generated report. The real backend should stream the stored file.
   */
  route("GET", "/reports/history/:id/download", ({ params }): Blob => {
    const record = db.reportHistory.find((r) => r.id === params.id);
    if (!record) throw new MockHttpError(404, "Generated report not found.");
    const lines = [
      ["Report", "Period", "Format", "Generated By", "Generated At"],
      [record.reportName, record.period, record.format, record.generatedBy, record.generatedAt],
    ];
    const csv = lines.map((l) => l.map((v) => `"${String(v).replace(/"/g, '""')}"`).join(",")).join("\r\n");
    return new Blob([csv], { type: "text/csv" });
  }),
];
