"use client";

import { useState } from "react";
import Link from "next/link";
import { useSearchParams } from "next/navigation";
import { Download, ExternalLink, FileChartColumn, FileText, History } from "lucide-react";
import { PageHeader } from "@/components/layout/PageHeader";
import { Badge } from "@/components/ui/Badge";
import { Button } from "@/components/ui/Button";
import { Card, CardHeader } from "@/components/ui/Card";
import { Skeleton } from "@/components/ui/Skeleton";
import { Tabs } from "@/components/ui/Tabs";
import { DataTable, type Column } from "@/components/tables/DataTable";
import { EmptyState } from "@/components/shared/EmptyState";
import { ErrorState } from "@/components/shared/ErrorState";
import { SearchInput } from "@/components/shared/SearchInput";
import { StatusBadge } from "@/components/shared/StatusBadge";
import { useDebouncedValue } from "@/hooks/useDebouncedValue";
import { useNotify } from "@/hooks/useNotify";
import { saveDownloadedFile } from "@/lib/api/api-client";
import { getErrorMessage } from "@/lib/api/error-handler";
import { reportsService } from "@/services/reports.service";
import { formatDate, formatDateTime } from "@/lib/utils/format";
import { useGetReportHistoryQuery, useGetReportsQuery } from "../services/reportsApi";
import { REPORT_CATEGORIES, type GeneratedReport, type ReportCategory, type ReportDefinition } from "../types";
import { GenerateReportModal } from "./GenerateReportModal";

const historyColumns: Column<GeneratedReport>[] = [
  { key: "name", header: "Report", cell: (r) => <span className="font-medium text-gray-900">{r.reportName}</span> },
  { key: "period", header: "Period", cell: (r) => r.period },
  { key: "format", header: "Format", cell: (r) => <Badge tone="gray">{r.format}</Badge>, hideBelow: "md" },
  { key: "by", header: "Generated By", cell: (r) => r.generatedBy, hideBelow: "lg" },
  { key: "at", header: "Generated", cell: (r) => <span className="whitespace-nowrap">{formatDateTime(r.generatedAt)}</span>, hideBelow: "md" },
  { key: "status", header: "Status", align: "center", cell: (r) => <StatusBadge status={r.status} /> },
];

/** Downloads a generated report file through the reports service. */
function DownloadButton({ report }: { report: GeneratedReport }) {
  const notify = useNotify();
  const [busy, setBusy] = useState(false);
  const onClick = async () => {
    setBusy(true);
    try {
      saveDownloadedFile(await reportsService.download(report));
    } catch (err) {
      notify("error", "Unable to download the report", getErrorMessage(err));
    } finally {
      setBusy(false);
    }
  };
  return (
    <Button variant="outline" size="sm" onClick={onClick} loading={busy} disabled={busy || report.status !== "Ready"} aria-label={`Download ${report.reportName}`}>
      {!busy && <Download className="size-3.5" />} Download
    </Button>
  );
}

const historyColumnsWithActions: Column<GeneratedReport>[] = [
  ...historyColumns,
  { key: "actions", header: <span className="sr-only">Actions</span>, align: "right", cell: (r) => <DownloadButton report={r} /> },
];

function isCategory(value: string | null): value is ReportCategory {
  return !!value && (REPORT_CATEGORIES as readonly string[]).includes(value);
}

export function ReportsView() {
  const searchParams = useSearchParams();
  const initial = searchParams.get("category");
  const [category, setCategory] = useState<ReportCategory | "">(isCategory(initial) ? initial : "");
  const [search, setSearch] = useState("");
  const [generating, setGenerating] = useState<ReportDefinition | null>(null);
  const debouncedSearch = useDebouncedValue(search);

  const reports = useGetReportsQuery({ category, search: debouncedSearch });
  const history = useGetReportHistoryQuery();
  const loading = reports.isLoading || reports.isFetching;

  return (
    <>
      <PageHeader title="Reports" description="Browse, generate and open eBudget reports." />

      <Card className="mb-5 overflow-hidden">
        <div className="flex flex-col gap-3 px-5 pt-4 lg:flex-row lg:items-center lg:justify-between">
          <h2 className="text-lg font-semibold text-gray-900">Report Catalog</h2>
          <SearchInput value={search} onChange={setSearch} placeholder="Search reports" label="Search reports" className="lg:w-80" />
        </div>
        <Tabs
          label="Report category"
          className="mt-2 px-5"
          value={category}
          onChange={setCategory}
          items={[{ value: "" as const, label: "All" }, ...REPORT_CATEGORIES.map((c) => ({ value: c, label: c }))]}
        />
        {reports.error && !loading ? (
          <ErrorState error={reports.error} onRetry={reports.refetch} />
        ) : (
          <div className="grid gap-4 p-5 md:grid-cols-2 2xl:grid-cols-3">
            {loading &&
              Array.from({ length: 6 }, (_, i) => <Skeleton key={i} className="h-40 w-full rounded-xl" />)}
            {!loading &&
              reports.data?.map((r) => (
                <article key={r.id} className="flex flex-col rounded-xl border border-gray-200 p-4 transition-shadow hover:shadow-md">
                  <div className="flex items-start gap-3">
                    <span className="flex size-10 shrink-0 items-center justify-center rounded-lg bg-brand-50 text-brand-600">
                      {r.category === "BFARS" ? <FileChartColumn className="size-5" /> : <FileText className="size-5" />}
                    </span>
                    <div className="min-w-0">
                      <h3 className="font-semibold text-gray-900">{r.name}</h3>
                      <p className="mt-0.5 line-clamp-2 text-sm text-gray-600">{r.description}</p>
                    </div>
                  </div>
                  <div className="mt-3 flex flex-wrap items-center gap-2 text-xs text-gray-500">
                    <Badge tone="gray">{r.category}</Badge>
                    <Badge tone="blue">{r.frequency}</Badge>
                    <span className="flex items-center gap-1">
                      <History className="size-3.5" />
                      {r.lastGeneratedAt ? `Last generated ${formatDate(r.lastGeneratedAt)}` : "Not yet generated"}
                    </span>
                  </div>
                  <div className="mt-4 flex gap-2 pt-1">
                    <Button size="sm" onClick={() => setGenerating(r)}>
                      Generate
                    </Button>
                    {r.href && (
                      <Link
                        href={r.href}
                        className="inline-flex h-8 items-center gap-1.5 rounded-lg border border-gray-300 px-3 text-xs font-medium text-gray-700 hover:bg-gray-50"
                      >
                        <ExternalLink className="size-3.5" /> Open
                      </Link>
                    )}
                  </div>
                </article>
              ))}
          </div>
        )}
        {!loading && reports.data?.length === 0 && (
          <EmptyState title="No reports match your search" description="Try another keyword or category." />
        )}
      </Card>

      <Card className="overflow-hidden">
        <CardHeader title="Recently Generated" description="Reports generated by your team" className="pb-4" />
        <DataTable
          columns={historyColumnsWithActions}
          rows={history.data}
          rowKey={(r) => r.id}
          loading={history.isLoading}
          error={history.error}
          onRetry={history.refetch}
          emptyTitle="No generated reports yet"
          caption="Generated reports"
        />
      </Card>

      <GenerateReportModal report={generating} onClose={() => setGenerating(null)} />
    </>
  );
}
