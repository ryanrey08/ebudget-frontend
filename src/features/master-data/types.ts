/**
 * eBudget master data, mirroring the backend's API Resources in
 * app/Http/Resources/Api/V1/EBudget (backend-api `main`). Every list is
 * paginated (`data`, `links`, `meta`) and normalised to `Paginated<T>`.
 * See docs/BACKEND_API_CHANGE_AUDIT.md for rules and error codes.
 */
import type { ActiveFilter, BackendPageQuery, IsoDate, IsoDateTime, Ulid } from "@/types/backend";

/* ── Fiscal years: /master-data/fiscal-years (ULID ids) ─────────────────── */

export type FiscalYearStatus = "open" | "closed" | "locked";

export interface FiscalYearRecord {
  id: Ulid;
  year: number;
  /** Always "FY <year>", generated by the database. */
  name: string;
  start_date: IsoDate;
  end_date: IsoDate;
  status: FiscalYearStatus;
  /** True only while the year is open. */
  is_editable: boolean;
  created_at: IsoDateTime;
  updated_at: IsoDateTime;
}

export interface FiscalYearQuery extends BackendPageQuery {
  status?: FiscalYearStatus;
}

export interface FiscalYearInput {
  year: number;
  start_date?: IsoDate | null;
  end_date?: IsoDate | null;
}

/** POST /{id}/close | /reopen | /lock */
export type FiscalYearTransition = "close" | "reopen" | "lock";

/* ── PREXC items: /master-data/prexc-items (integer ids) ───────────────── */

export interface PrexcItem {
  id: number;
  code: string;
  parent: { id: number; code: string; description: string } | null;
  /** A heading: groups items and never takes an amount. */
  is_parent_only: boolean;
  level: number;
  description: string;
  sort_order: number;
  is_active: boolean;
  children_count: number;
  created_at: IsoDateTime;
  updated_at: IsoDateTime;
}

export interface PrexcItemQuery extends BackendPageQuery {
  parent_id?: number;
  root?: 1;
  is_parent_only?: ActiveFilter;
  is_active?: ActiveFilter;
  level?: number;
  search?: string;
}

export interface PrexcItemInput {
  code?: string;
  parent_id?: number | null;
  is_parent_only?: boolean;
  level?: number;
  description?: string;
  sort_order?: number;
  is_active?: boolean;
}

